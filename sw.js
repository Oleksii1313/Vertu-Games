/*
 * Vert Games · service worker «сквозного» типа.
 *
 * Зачем он нужен: без service worker'а Chrome не предлагает «Установить
 * приложение», а без установленного приложения нельзя открыть платформу и игру
 * в отдельном окне без адресной строки браузера.
 *
 * Почему НИЧЕГО не кешируется: платформа правится часто, а игры и казино
 * критичны к свежести кода (множители колеса, ставки, версии страниц). Поэтому
 * запросы просто идут в сеть как обычно, а worker лишь делает приложение
 * устанавливаемым и не ломает обновления после деплоя.
 */
self.addEventListener('install', function (event) {
  self.skipWaiting();
});

self.addEventListener('activate', function (event) {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('fetch', function (event) {
  /* Ничего не подменяем и не кешируем: только разрешаем браузеру считать
     приложение устанавливаемым. Ошибки сети уходят в обычную обработку. */
  if (event.request.method !== 'GET') return;
});
